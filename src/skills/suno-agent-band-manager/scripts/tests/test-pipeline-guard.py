AUTO_LYRICS_PACKAGE = (
    "## Your Suno Package\n\n"
    "### Lyrics\nLyrics: Auto-generated by Suno — set Lyrics Mode to Auto\n\n"
    "### Style Prompt (v6)\n120/1000 characters\n\n```\nwarm folk, brushed drums\n```\n\n"
    "### Exclude Styles\n```\nautotune\n```\n\n"
    "### Settings\n- Model: v6\n\n"
    "### Song Title\n```\nPorch Light\n```\n\n"
    "### Save to\nPaper Lanterns\n\n"
    "### Wild Card Variant — The Unexpected Take\n```\n1960s coffeehouse folk\n```\n"
)

TAGGED_PACKAGE = AUTO_LYRICS_PACKAGE.replace(
    "Lyrics: Auto-generated by Suno — set Lyrics Mode to Auto",
    "```\n[Verse 1]\nThe porch light flickers on\n\n[Chorus]\nCome back home\n```",
)

INSTRUMENTAL_PACKAGE = AUTO_LYRICS_PACKAGE.replace(
    "Lyrics: Auto-generated by Suno — set Lyrics Mode to Auto",
    "Lyrics: Instrumental (no vocals)\n[Intro]\n[Build]",
)


def test_auto_lyrics_package_needs_no_lyric_transformer():
    assert not mod.needs_lyric_transformer(AUTO_LYRICS_PACKAGE)
    missing, order = mod.build_violations(AUTO_LYRICS_PACKAGE, {mod.STYLE_SKILL})
    assert missing == [] and order == []


def test_instrumental_package_needs_no_lyric_transformer():
    assert not mod.needs_lyric_transformer(INSTRUMENTAL_PACKAGE)


def test_tagged_lyrics_need_lyric_transformer():
    assert mod.needs_lyric_transformer(TAGGED_PACKAGE)
    missing, _ = mod.build_violations(TAGGED_PACKAGE, {mod.STYLE_SKILL})
    assert missing == [mod.LYRIC_SKILL]


def test_lyrics_only_refinement_needs_no_style_builder():
    msg = (
        "## Paper Lanterns Refinement Update\n### What Changed\n- tighter chorus\n\n"
        "### Copy-Ready Lyrics\n```\n[Chorus]\nCome back home\n```\n"
    )
    assert mod.detect_suno_package(msg)
    missing, _ = mod.build_violations(msg, {mod.LYRIC_SKILL})
    assert missing == []


def test_headingless_package_still_needs_style_builder():
    msg = "Here you go — paste into Suno: warm folk, brushed drums"
    assert mod.needs_style_builder(msg)


