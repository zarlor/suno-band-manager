import json as _json


def _user(text, **extra):
    return _json.dumps({"type": "user", "message": {"role": "user", "content": text}, **extra})


def _skill(name):
    return _json.dumps({"type": "assistant", "message": {"content": [
        {"type": "tool_use", "name": "Skill", "input": {"skill": name}}]}})


def _agent(prompt):
    return _json.dumps({"type": "assistant", "message": {"content": [
        {"type": "tool_use", "name": "Agent", "input": {"prompt": prompt}}]}})


def _tool_result():
    return _json.dumps({"type": "user", "message": {"content": [
        {"type": "tool_result", "content": "Launching skill"}]}})


def test_earlier_turn_invocation_does_not_count(tmp_path):
    path = _write_transcript(tmp_path, [
        _user("make me a song"),
        _skill("suno-style-prompt-builder"),
        _user("now another one"),
    ])
    assert mod.check_skill_invocations(path) == set()
    assert "suno-style-prompt-builder" in mod.check_skill_invocations(path, current_turn_only=False)


def test_tool_results_skill_bodies_and_notifications_do_not_reset_turn(tmp_path):
    path = _write_transcript(tmp_path, [
        _user("make me a song"),
        _skill("suno-style-prompt-builder"),
        _tool_result(),
        _json.dumps({"type": "user", "isMeta": True, "message": {"content": [
            {"type": "text", "text": "Base directory for this skill: ..."}]}}),
        _user("<task-notification>agent finished</task-notification>",
              origin={"kind": "task-notification"}, promptSource="system"),
        _user("Stop hook feedback: PIPELINE VIOLATION ..."),
        _agent("Invoke suno-lyric-transformer in headless mode with this poem"),
    ])
    assert mod.check_skill_invocations(path) == {
        "suno-style-prompt-builder", "suno-lyric-transformer"}


def test_agent_prompt_that_only_mentions_a_skill_does_not_count(tmp_path):
    path = _write_transcript(tmp_path, [
        _user("hi"),
        _agent("Summarize what suno-style-prompt-builder returned last week"),
    ])
    assert mod.check_skill_invocations(path) == set()


def test_main_passes_auto_lyrics_package_with_style_builder_this_turn(tmp_path, monkeypatch, capsys):
    import io
    path = _write_transcript(tmp_path, [_user("surprise me"), _skill("suno-style-prompt-builder")])
